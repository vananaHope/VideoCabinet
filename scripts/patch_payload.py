"""Generate Inno entries from the same ownership policy as runtime identity."""
import argparse
from fnmatch import fnmatchcase
from pathlib import Path
import stat

from my_video_manager.runtime_fingerprint import APP_OWNED_PATHS, FILENAME, load_runtime_fingerprint


def app_files(directory: Path) -> list[str]:
    """Return only app-owned regular files, rejecting unsafe Inno paths/links."""
    files = []
    for path in directory.rglob('*'):
        name = path.relative_to(directory).as_posix()
        if path.is_symlink() or getattr(path.lstat(), 'st_file_attributes', 0) & stat.FILE_ATTRIBUTE_REPARSE_POINT:
            raise ValueError(f'Reparse point in bundle: {name}')
        if not path.is_file():
            continue
        if any(fnmatchcase(name.lower(), pattern) for pattern in APP_OWNED_PATHS):
            if any(c in name for c in '\r\n"{};'):
                raise ValueError(f'Unsafe Inno path: {name}')
            files.append(name)
    required = {'my-video-manager.exe', FILENAME, 'THIRD-PARTY-NOTICES.txt',
                'my_video_manager/build-version.txt', 'my_video_manager/web/index.html'}
    if not required.issubset(files) or not any(name.startswith('licenses/') for name in files):
        raise ValueError('Incomplete application payload')
    return sorted(files, key=str.lower)


def write_patch_include(directory: Path, output: Path, version: str) -> list[str]:
    load_runtime_fingerprint(directory / FILENAME)
    if (directory / 'my_video_manager/build-version.txt').read_text(encoding='utf-8').strip() != version:
        raise ValueError('Patch version differs from bundled build-version.txt')
    files = app_files(directory)
    lines = ['; Generated by scripts/patch_payload.py. Do not edit.', '[Files]']
    for name in files:
        destination = str(Path(name).parent).replace('/', '\\')
        suffix = '' if destination == '.' else '\\' + destination
        source = name.replace('/', '\\')
        lines.append(f'Source: "{{#AppDirectory}}\\{source}"; DestDir: "{{app}}{suffix}"; Flags: ignoreversion')
    lines += [f'Source: "{{#AppDirectory}}\\{FILENAME}"; DestName: "patch-expected.json"; Flags: dontcopy',
              '[InstallDelete]']
    # Replace whole app-owned trees so removed hashed assets/modules/metadata do
    # not survive an update. Individual files use Inno's normal replacement.
    for pattern in APP_OWNED_PATHS:
        if pattern.endswith('/**'):
            root = pattern[:-3].replace('/', '\\')
            lines.append(f'Type: filesandordirs; Name: "{{app}}\\{root}"')
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_suffix(output.suffix + '.tmp')
    try:
        temporary.write_text('\n'.join(lines) + '\n', encoding='utf-8-sig')
        temporary.replace(output)
    finally:
        temporary.unlink(missing_ok=True)
    return files


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--version', required=True)
    args = parser.parse_args()
    selected = write_patch_include(args.directory, args.output, args.version)
    print(f'Patch payload: {len(selected)} files, '
          f'{sum((args.directory / name).stat().st_size for name in selected)} bytes')
